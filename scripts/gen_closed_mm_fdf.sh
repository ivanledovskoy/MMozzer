#!/bin/bash
# gen_closed_mm_fdf.sh - turn the extracted vendor modules (closed_mm/modules.txt)
# into an FDF include that embeds each one as a MM_STANDALONE FFS file with a
# TRUE depex (so our MM dispatcher loads them regardless of vendor dependencies).
#
# Output: closed_mm/ClosedMm.fdf.inc  (included by SbsaQemuStandaloneMm.fdf
#         under !if $(CLOSED_MM) == TRUE). Paths resolve via PACKAGES_PATH
#         ($MMOZZER root), same as the rest of the stand.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"

MANIFEST="$ROOT/closed_mm/modules.txt"
OUT="$ROOT/closed_mm/ClosedMm.fdf.inc"
DEPEX="closed_mm/closed_mm_true.depex"

[ -f "$MANIFEST" ] || { echo "!! no manifest: $MANIFEST (run extract_closed_mm.sh first)" >&2; exit 1; }

{
  echo "## Auto-generated by scripts/gen_closed_mm_fdf.sh - DO NOT EDIT."
  echo "## Vendor StandaloneMM modules, embedded with a TRUE depex (always dispatch)."
  while IFS=, read -r guid name file; do
    case "$guid" in '#'*|'') continue;; esac
    printf '\nFILE MM_STANDALONE = %s {\n' "$guid"
    printf '  SECTION SMM_DEPEX = %s\n' "$DEPEX"
    printf '  SECTION PE32 = closed_mm/modules/%s\n' "$file"
    printf '  SECTION UI = "%s"\n' "$name"
    printf '}\n'
  done < "$MANIFEST"
} > "$OUT"

echo "=> $OUT ($(grep -c '^FILE ' "$OUT") modules)"
